// Writes src/views/icons.ts from Lucide (https://lucide.dev, ISC licence).
// Only the icons listed here end up in the Worker. Run: node scripts/build-icons.mjs
import fs from "node:fs";
import path from "node:path";

const NAMES = [
  "messages-square", "bell", "shield", "file-text", "scale", "book-open", "external-link",
  "plus", "heart", "smile-plus", "link", "reply", "paperclip", "eye", "eye-off", "circle-check",
  "pin", "lock", "settings", "log-out", "log-in", "chevron-left", "chevron-right", "x", "menu",
  "download", "file-archive", "file", "box", "image", "ban", "rotate-ccw", "trash-2", "user-round",
  "search", "circle-help", "quote", "archive", "rss",
];

const dir = path.join(import.meta.dirname, "../node_modules/lucide-static/icons");
const inner = {};
for (const name of NAMES) {
  const svg = fs.readFileSync(path.join(dir, `${name}.svg`), "utf8");
  inner[name] = svg.slice(svg.indexOf(">", svg.indexOf("<svg")) + 1, svg.lastIndexOf("</svg>")).replace(/\s*\n\s*/g, "").trim();
}

const out = `// Generated by scripts/build-icons.mjs from lucide-static. Lucide is ISC-licensed: https://lucide.dev/license
import { raw } from "hono/html";

const PATHS = ${JSON.stringify(inner, null, 2)} as const;

export type IconName = keyof typeof PATHS;

/** An inline Lucide icon. Decorative unless a label is given. */
export function icon(name: IconName, opts: { size?: number; label?: string; class?: string } = {}) {
  const size = opts.size ?? 18;
  const a11y = opts.label ? \`role="img" aria-label="\${opts.label.replace(/"/g, "&quot;")}"\` : 'aria-hidden="true"';
  return raw(
    \`<svg class="icon\${opts.class ? " " + opts.class : ""}" width="\${size}" height="\${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" \${a11y}>\${PATHS[name]}</svg>\`,
  );
}
`;
fs.writeFileSync(path.join(import.meta.dirname, "../src/views/icons.ts"), out);
console.log(`wrote ${NAMES.length} icons`);
